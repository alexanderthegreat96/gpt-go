#!/usr/bin/env python3
"""
WARNING: This script has been auto-generated by CLAUDE OPUS
Reference activation dumper for the Go GPT-2 loader.

This is a throwaway script. It exists for one reason: loading somebody else's
weights fails silently. Get a transpose backwards, use the erf GELU where the
tanh one belongs, split the fused QKV wrong, and the Go model still runs and
still emits grammatical English. It just emits the WRONG grammatical English,
which is indistinguishable from an undertrained model.

So we take a known-good PyTorch GPT-2, hook every interesting point in the
forward pass for a fixed prompt, and write those tensors out. Then
`verify-gpt2` runs the same tokens through the Go implementation and diffs them
layer by layer. "block 3 attention diverges" is a bug you can fix in an
afternoon; "the output is garbage" is a week.

Run it once, keep the output, delete the Python.

    pip install torch transformers safetensors
    python scripts/dump_gpt2_reference.py

Outputs (next to the weights, by default under models/gpt2/):
    model.safetensors                  the weights themselves
    reference_activations.safetensors   what every layer should produce

The tensor names here MUST match the ones in gpt/verify.go. If you add a
capture point, add it in both files.
"""

import argparse
import os

import torch
from safetensors.torch import save_file
from transformers import GPT2LMHeadModel

# the tokenizer is imported lazily, inside the branch that needs it. importing
# it up here would defeat the whole point of --tokens -> transformers has moved
# the slow tokenizers around between major versions, and a missing class would
# kill the script even when we are not tokenizing anything


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--model",
        default="gpt2",
        help=(
            "HuggingFace model id (gpt2, gpt2-medium, gpt2-large, gpt2-xl) OR a local "
            "directory holding config.json plus model.safetensors. Use the local form "
            "when you already have the weights and do not want to download them twice."
        ),
    )
    parser.add_argument(
        "--prompt",
        default="The area of Antarctica is",
        help="Prompt to run through the model",
    )
    parser.add_argument(
        "--tokens",
        default=None,
        help=(
            "Comma separated token ids to use instead of tokenizing --prompt. Lets you "
            "dump a reference without vocab.json/merges.txt present, and lets you reuse "
            "the exact ids from an earlier dump. Every GPT-2 size shares one tokenizer, "
            "so ids from a gpt2 dump are valid for gpt2-medium and friends."
        ),
    )
    parser.add_argument(
        "--out-dir",
        default=os.path.join("models", "gpt2"),
        help="Where to write the weights and the activation dump",
    )
    return parser.parse_args()


def check_existing_weights(path, config):
    """Refuse to pair a reference dump with weights from a different model.

    This exists because of a real afternoon lost to it: a leftover
    gpt2-medium checkpoint sitting where gpt2 was expected meant the reference
    described a 12 layer, 768 wide model while the weights were 24 layers and
    1024 wide. Every tensor mismatched, which looks exactly like a transposed
    matrix, so that is what got debugged. Shapes are cheap to check.
    """
    from safetensors import safe_open

    with safe_open(path, framework="pt") as handle:
        keys = list(handle.keys())

        wte = next((k for k in ("wte.weight", "transformer.wte.weight") if k in keys), None)
        if wte is None:
            raise SystemExit(
                f"\n{path} does not look like a GPT-2 checkpoint (no wte.weight).\n"
                f"Delete it and re-run, or point --out-dir somewhere else."
            )

        found_embd = handle.get_slice(wte).get_shape()[1]

    found_layers = len({k.split(".")[1] for k in keys if k.startswith("h.")})
    if found_layers == 0:
        found_layers = len({k.split(".")[2] for k in keys if k.startswith("transformer.h.")})

    if found_embd == config.n_embd and found_layers == config.n_layer:
        return

    raise SystemExit(
        f"\nThe weights already at {path} are not the model you asked for.\n"
        f"  on disk : {found_layers} layers, {found_embd} wide\n"
        f"  wanted  : {config.n_layer} layers, {config.n_embd} wide (from {config.name_or_path or 'the requested model'})\n"
        f"\nPairing those would make every tensor in verify-gpt2 mismatch for no good reason.\n"
        f"Either delete the file and re-run, or dump a reference for the model you already have:\n"
        f"  rm {path} && make gpt2-reference\n"
    )


def main():
    args = parse_args()
    os.makedirs(args.out_dir, exist_ok=True)

    print(f"Loading {args.model}...")
    model = GPT2LMHeadModel.from_pretrained(args.model)
    model.eval()

    # float32 everywhere. the Go side widens F16/BF16 on read, but keeping the
    # reference in full precision means a diff we see is OUR bug and not a
    # rounding artifact we have to reason about
    model = model.to(torch.float32)

    if args.tokens:
        # explicit ids -> no tokenizer needed at all, which means a local model
        # directory only has to carry config.json and the weights
        token_ids = [int(t.strip()) for t in args.tokens.split(",") if t.strip()]
        prompt = args.prompt
        print(f"Tokens : {token_ids} (given explicitly, --prompt not tokenized)")
    else:
        from transformers import AutoTokenizer

        tokenizer = AutoTokenizer.from_pretrained(args.model)
        token_ids = tokenizer.encode(args.prompt)
        prompt = args.prompt
        print(f"Prompt : {prompt!r}")
        print(f"Tokens : {token_ids}")

    if not token_ids:
        raise SystemExit("No tokens to run -> give a non-empty --prompt or --tokens")

    input_ids = torch.tensor([token_ids], dtype=torch.long)

    # what we capture, keyed exactly as gpt/verify.go expects
    captured = {}

    def keep(name):
        """Returns a hook that stores a module's output under `name`."""

        def hook(_module, _inputs, output):
            # attention blocks hand back a tuple of (output, present, ...)
            tensor = output[0] if isinstance(output, tuple) else output
            # drop the batch dimension -> our Matrix is 2D, seq x features
            captured[name] = tensor.detach()[0].clone()

        return hook

    transformer = model.transformer
    handles = []

    # the embedding sum. there is no single module whose output is wte + wpe,
    # so we take the input to block 0 instead, which is the same tensor
    def keep_block_input(_module, inputs, _output):
        captured["embed"] = inputs[0].detach()[0].clone()

    handles.append(transformer.h[0].register_forward_hook(keep_block_input))

    for i, block in enumerate(transformer.h):
        handles.append(block.ln_1.register_forward_hook(keep(f"h.{i}.ln_1")))
        handles.append(block.attn.register_forward_hook(keep(f"h.{i}.attn")))
        handles.append(block.ln_2.register_forward_hook(keep(f"h.{i}.ln_2")))
        handles.append(block.mlp.register_forward_hook(keep(f"h.{i}.mlp")))
        handles.append(block.register_forward_hook(keep(f"h.{i}.out")))

    handles.append(transformer.ln_f.register_forward_hook(keep("ln_f")))

    print("Running the forward pass...")
    with torch.no_grad():
        outputs = model(input_ids)

    captured["logits"] = outputs.logits.detach()[0].clone()

    for handle in handles:
        handle.remove()

    # res1 is the first residual add, which also has no module of its own.
    # GPT-2 computes it as block_input + attn_output, so we reconstruct it.
    # for block i > 0 the input is the previous block's output
    for i in range(len(transformer.h)):
        block_input = captured["embed"] if i == 0 else captured[f"h.{i - 1}.out"]
        captured[f"h.{i}.res1"] = block_input + captured[f"h.{i}.attn"]

    # safetensors wants contiguous tensors and string-only metadata
    tensors = {name: tensor.contiguous() for name, tensor in captured.items()}

    # the token ids ride along inside the dump. this is deliberate: the Go side
    # does not have GPT-2's byte-level BPE yet, and even once it does, a
    # tokenizer bug would otherwise show up looking like a model bug
    metadata = {
        "tokens": ",".join(str(t) for t in token_ids),
        "prompt": prompt,
        "model": args.model,
        # the shape goes in too, so the Go side can tell you the two files are
        # different models without having to infer it from tensor shapes
        "n_layer": str(model.config.n_layer),
        "n_embd": str(model.config.n_embd),
    }

    activations_path = os.path.join(args.out_dir, "reference_activations.safetensors")
    save_file(tensors, activations_path, metadata=metadata)
    print(f"Wrote {len(tensors)} reference tensors to {activations_path}")

    # and the weights, so the Go loader has something to load. saving them from
    # here rather than downloading them separately guarantees the two files
    # describe the same model
    weights_path = os.path.join(args.out_dir, "model.safetensors")
    if os.path.exists(weights_path):
        # a file being present is NOT good enough -> if it came from a
        # different GPT-2 size than the one we just dumped a reference for,
        # every tensor in the comparison mismatches and it reads like a
        # transpose bug. check the shapes and refuse rather than guess
        check_existing_weights(weights_path, model.config)
        print(f"Weights already present at {weights_path} and they match, leaving them alone")
    else:
        state = {k: v.contiguous() for k, v in model.state_dict().items()}
        # the causal mask buffers are not parameters and the Go loader does not
        # want them -> it builds the mask itself
        state = {
            k: v
            for k, v in state.items()
            if not k.endswith(".attn.bias") and not k.endswith(".attn.masked_bias")
        }
        save_file(state, weights_path, metadata={"format": "pt"})
        print(f"Wrote weights to {weights_path}")

    print()
    print("Now verify the Go side against it:")
    print(f"  go run main.go verify-gpt2 -w {weights_path} -r {activations_path}")


if __name__ == "__main__":
    main()
